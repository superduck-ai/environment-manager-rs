GO_FUNCTION = re.compile(
    r"^func\s+(?:(?:\((?P<receiver>[^)]*)\)\s+))?"
    r"(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*(?:\[[^]]+\]\s*)?\("
)
RUST_FUNCTION = re.compile(
    r"^\s*(?:pub(?:\([^)]*\))?\s+)?"
    r"(?:(?:default|const|async|unsafe)\s+)*"
    r"(?:extern(?:\s+\"[^\"]+\")?\s+)?"
    r"fn\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*(?:<[^;{]*>)?\s*\("
)
RUST_CONTEXT_START = re.compile(
    r"^\s*(?:(?:pub(?:\([^)]*\))?|unsafe)\s+)?(?P<kind>impl|trait)\b"
)
GENERATED_PROTO_HEADER = "Code generated by protoc-gen-go. DO NOT EDIT."

CSV_HEADER = [
    "go_path",
    "kind",
    "go_symbol",
    "expected_rust_path",
    "rust_path",
    "rust_line",
    "rust_symbol",
    "status",
    "detail",
]
INCOMPLETE_STATUSES = frozenset(
    {
        "pending",
        "symbol-missing",
        "ambiguous",
        "name-only-match",
        "generated-wrapper-missing",
    }
)


@dataclass(frozen=True)
class RustSymbol:
    """从仓库内一个 Rust 声明恢复出的实际位置与 owner。"""

    path: Path
    line: int
    name: str
    owner: str | None
    declaration_kind: str
    documentation: str
    is_test_entry: bool

    @property
    def display_name(self) -> str:
        """返回 CSV 使用的真实 Rust 符号名。"""

        return f"{self.owner}::{self.name}" if self.owner else self.name

    @property
    def location(self) -> str:
        """返回歧义诊断使用的稳定路径、行号和符号。"""

        return (
            f"{self.path.as_posix()}:{self.line}:{self.display_name}"
            f"[{self.declaration_kind}]"
        )


@dataclass(frozen=True)
class RustContext:
    """当前 Rust impl/trait block 的 owner 与花括号深度。"""

    body_depth: int
    owner: str
    declaration_kind: str


def snake_case(name: str) -> str:
    """按 Rust 常用规则转换 CamelCase，并稳定处理连续缩写。"""

    first = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    second = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", first)
    return second.replace("-", "_").lower()


def receiver_type(receiver: str | None) -> str | None:
    """从 Go receiver 声明中提取去除指针和泛型装饰后的类型名。"""

    if receiver is None:
        return None
    parts = receiver.strip().split()
    if not parts:
        return None
    raw = parts[-1].lstrip("*")
    return raw.split("[", 1)[0]


def expected_rust_path(relative: Path) -> Path:
    """返回旧布局下的机械期望路径；实际命中路径由符号索引决定。"""

    if relative == Path("main.go"):
        return Path("src/main.rs")
    return Path("src") / relative.with_suffix(".rs")


def mask_rust_non_code(source: str) -> str:
    """屏蔽 Rust 注释和字符串，同时保持长度与换行以可靠计算 block 深度。"""

    output = list(source)
    length = len(source)
    index = 0
    block_comment_depth = 0

    def mask(start: int, end: int) -> None:
        for position in range(start, end):
            if output[position] not in {"\n", "\r"}:
                output[position] = " "

    while index < length:
        if block_comment_depth:
            if source.startswith("/*", index):
                block_comment_depth += 1
                mask(index, index + 2)
                index += 2
            elif source.startswith("*/", index):
                block_comment_depth -= 1
                mask(index, index + 2)
                index += 2
            else:
                mask(index, index + 1)
                index += 1
            continue

        if source.startswith("//", index):
            end = source.find("\n", index)
            if end == -1:
                end = length
            mask(index, end)
            index = end
            continue
        if source.startswith("/*", index):
            block_comment_depth = 1
            mask(index, index + 2)
            index += 2
            continue

        raw_match = re.match(r"(?:b)?r(?P<hashes>#{0,255})\"", source[index:])
        if raw_match is not None:
            terminator = '"' + raw_match.group("hashes")
            content_start = index + raw_match.end()
            close = source.find(terminator, content_start)
            end = length if close == -1 else close + len(terminator)
            mask(index, end)
            index = end
            continue

        string_prefix_length = 0
        if source[index] == '"':
            string_prefix_length = 1
        elif index + 1 < length and source[index] in {"b", "c"} and source[index + 1] == '"':
            string_prefix_length = 2
        if string_prefix_length:
            end = index + string_prefix_length
            escaped = False
            while end < length:
                character = source[end]
                end += 1
                if escaped:
                    escaped = False
                elif character == "\\":
                    escaped = True
                elif character == '"':
                    break
            mask(index, end)
            index = end
            continue

        # 只屏蔽有闭合单引号的字符字面量；`'a` lifetime 保持为代码。
        if source[index] == "'":
            end = index + 1
            if end < length and source[end] == "\\":
                end += 2
            else:
                end += 1
            if end < length and source[end] == "'":
                end += 1
                mask(index, end)
                index = end
                continue

        index += 1

    return "".join(output)


def context_metadata(header: str, kind: str) -> tuple[str | None, str]:
    """提取 impl/trait owner，并区分固有实现、trait 实现和 trait 声明。"""

    compact = " ".join(header.replace("{", " ").split())
    if kind == "trait":
        match = re.search(r"\btrait\s+([A-Za-z_][A-Za-z0-9_]*)", compact)
        return (
            match.group(1) if match is not None else None,
            "trait-definition",
        )

    # Trait impl 的 self type 位于最后一个 `for` 后；泛型 where clause 不属于类型名。
    matches = list(
        re.finditer(
            r"\bfor\s+(?:&(?:'[_A-Za-z][_A-Za-z0-9]*\s+)?)?"
            r"(?:[A-Za-z_][A-Za-z0-9_]*::)*(?P<owner>[A-Za-z_][A-Za-z0-9_]*)",
            compact,
        )
    )
    if matches:
        return matches[-1].group("owner"), "trait-impl"

    remainder = re.sub(r"^\s*(?:unsafe\s+)?impl\b", "", compact, count=1).lstrip()
    if remainder.startswith("<"):
        depth = 0
        for index, character in enumerate(remainder):
            if character == "<":
                depth += 1
            elif character == ">":
                depth -= 1
                if depth == 0:
                    remainder = remainder[index + 1 :].lstrip()
                    break
    match = re.match(
        r"(?:[A-Za-z_][A-Za-z0-9_]*::)*(?P<owner>[A-Za-z_][A-Za-z0-9_]*)",
        remainder,
    )
    return (
        match.group("owner") if match is not None else None,
        "inherent-impl",
    )


def rust_symbols(path: Path, rust_root: Path) -> list[RustSymbol]:
    """提取单个 Rust 文件中的自由函数、trait 方法和 impl 方法及真实 owner。"""

    source = path.read_text(encoding="utf-8")
    code_lines = mask_rust_non_code(source).splitlines()
    original_lines = source.splitlines()
    relative = path.relative_to(rust_root)
    symbols: list[RustSymbol] = []
    contexts: list[RustContext] = []
    pending_context: tuple[str, int, list[str]] | None = None
    brace_depth = 0

    for line_number, (original_line, code_line) in enumerate(
        zip(original_lines, code_lines, strict=True), start=1
    ):
        while contexts and brace_depth < contexts[-1].body_depth:
            contexts.pop()

        if pending_context is None:
            context_match = RUST_CONTEXT_START.match(code_line)
            if context_match is not None:
                pending_context = (context_match.group("kind"), brace_depth, [code_line])
        else:
            pending_context[2].append(code_line)

        if pending_context is not None and "{" in code_line:
            kind, start_depth, header_lines = pending_context
            owner, declaration_kind = context_metadata(" ".join(header_lines), kind)
            if owner is not None:
                contexts.append(
                    RustContext(start_depth + 1, owner, declaration_kind)
                )
            pending_context = None

        function_match = RUST_FUNCTION.match(original_line)
        if function_match is not None:
            owner = contexts[-1].owner if contexts else None
            declaration_kind = (
                contexts[-1].declaration_kind if contexts else "free"
            )
            documentation = preceding_documentation(original_lines, line_number - 1)
            symbols.append(
                RustSymbol(
                    path=relative,
                    line=line_number,
                    name=function_match.group("name"),
                    owner=owner,
                    declaration_kind=declaration_kind,
                    documentation=documentation,
                    is_test_entry=preceding_test_attribute(
                        original_lines, line_number - 1
                    ),
                )
            )

        brace_depth += code_line.count("{") - code_line.count("}")

    return symbols


def preceding_documentation(lines: list[str], function_index: int) -> str:
    """读取函数前连续的 Rust doc comments，并跨过紧邻的 attribute。"""

    comments: list[str] = []
    cursor = function_index - 1
    while cursor >= 0:
        stripped = lines[cursor].strip()
        if stripped.startswith("///"):
            comments.append(stripped.removeprefix("///").strip())
        elif stripped.startswith("#[") or (comments and not stripped):
            pass
        else:
            break
        cursor -= 1
    comments.reverse()
    return "\n".join(comments)


def preceding_test_attribute(lines: list[str], function_index: int) -> bool:
    """判断函数紧邻属性中是否包含内建或 Tokio 测试入口。"""

    cursor = function_index - 1
    while cursor >= 0:
        stripped = lines[cursor].strip()
        if re.match(r"#\[(?:tokio::)?test(?:\s*\(|\s*\])", stripped):
            return True
        if stripped.startswith("#[") or stripped.startswith("///") or not stripped:
            cursor -= 1
            continue
        return False
    return False


def build_rust_index(rust_root: Path) -> dict[str, list[RustSymbol]]:
    """按函数名索引仓库内全部 Rust 源码声明。"""

    index: dict[str, list[RustSymbol]] = {}
    for path in sorted((rust_root / "src").rglob("*.rs")):
        for symbol in rust_symbols(path, rust_root):
            index.setdefault(symbol.name, []).append(symbol)
    return index


def is_within(path: Path, parent: Path) -> bool:
    """兼容 Python 3.10 地判断相对路径是否位于给定目录。"""

    try:
        path.relative_to(parent)
    except ValueError:
        return False
    return True


def deduplicate(symbols: Iterable[RustSymbol]) -> list[RustSymbol]:
    """按实际声明位置去重，同时保持扫描顺序稳定。"""

    seen: set[tuple[Path, int, str, str | None, str]] = set()
    result: list[RustSymbol] = []
    for symbol in symbols:
        identity = (
            symbol.path,
            symbol.line,
            symbol.name,
            symbol.owner,
            symbol.declaration_kind,
        )
        if identity not in seen:
            seen.add(identity)
            result.append(symbol)
    return result


def receiver_matches(go_receiver: str | None, rust_owner: str | None) -> bool:
    """比较 Go receiver 与 Rust impl owner，允许大小写和缩写采用 Rust snake case。"""

    if go_receiver is None:
        return rust_owner is None
    if rust_owner is None:
        return False
    return snake_case(go_receiver) == snake_case(rust_owner.removeprefix("r#"))


def candidates_in_scope(
    candidates: Iterable[RustSymbol], expected: Path
) -> list[RustSymbol]:
    """只保留同一 Go package 对应 Rust module 子树内的候选，避免跨包同名误报。"""

    scope = expected.parent
    return [candidate for candidate in candidates if is_within(candidate.path, scope)]


def choose_unique(
    candidates: list[RustSymbol], expected: Path
) -> tuple[RustSymbol | None, list[RustSymbol]]:
    """优先期望文件和固有 impl；其余情况要求 package scope 内全局唯一。"""

    candidates = deduplicate(candidates)
    exact_file = [candidate for candidate in candidates if candidate.path == expected]
    if len(exact_file) == 1:
        return exact_file[0], []
    if len(exact_file) > 1:
        inherent = [
            candidate
            for candidate in exact_file
            if candidate.declaration_kind == "inherent-impl"
        ]
        if len(inherent) == 1:
            return inherent[0], []
        return None, exact_file
    if len(candidates) == 1:
        return candidates[0], []
    inherent = [
        candidate
        for candidate in candidates
        if candidate.declaration_kind == "inherent-impl"
    ]
    if len(inherent) == 1:
        return inherent[0], []
    return None, candidates


def candidate_detail(candidates: Iterable[RustSymbol]) -> str:
    """把歧义候选限制在可读长度内写入 CSV。"""

    locations = [candidate.location for candidate in candidates]
    visible = locations[:8]
    suffix = f"; ... and {len(locations) - 8} more" if len(locations) > 8 else ""
    return "; ".join(visible) + suffix


def documentation_mentions(
    symbol: RustSymbol, go_name: str, go_receiver: str | None
) -> bool:
    """只接受 code span 中的显式 Go 符号证据，拒绝普通文字里的泛化同名词。"""

    code_spans = re.findall(r"`([^`]+)`", symbol.documentation)
    if go_receiver is None:
        return any(span == go_name for span in code_spans)
    if not receiver_matches(go_receiver, symbol.owner):
        return False
    return any(
        re.search(
            rf"(?<![A-Za-z0-9_]){re.escape(go_name)}(?:\(\))?(?![A-Za-z0-9_])",
            span,
        )
        is not None
        for span in code_spans
    )


def associated_constructor_candidates(
    go_name: str,
    go_receiver: str | None,
    expected: Path,
    rust_index: dict[str, list[RustSymbol]],
) -> list[RustSymbol]:
    """识别严格的 Go `NewFoo` 到 Rust `Foo::new` 现代构造器映射。"""

    if go_receiver is not None:
        return []
    match = re.fullmatch(r"New(?P<owner>[A-Z][A-Za-z0-9_]*)", go_name)
    if match is None:
        return []
    owner = match.group("owner")
    return [
        candidate
        for candidate in candidates_in_scope(rust_index.get("new", []), expected)
        if receiver_matches(owner, candidate.owner)
    ]


def symbol_row(
    *,
    go_location: str,
    kind: str,
    go_symbol: str,
    go_name: str,
    go_receiver: str | None,
    expected: Path,
    rust_index: dict[str, list[RustSymbol]],
    all_rust_symbols: list[RustSymbol],
    scope_exists: bool,
) -> list[str]:
    """为一个 Go 声明生成保守映射；不确定候选绝不标记 migrated。"""

    mechanical_name = snake_case(go_name)
    candidate_names = [mechanical_name]
    if go_name != mechanical_name:
        # 一些兼容测试有意保留 Go 名；只有真实声明存在时才会命中。
        candidate_names.append(go_name)
    named = candidates_in_scope(
        (
            candidate
            for candidate_name in candidate_names
            for candidate in rust_index.get(candidate_name, [])
        ),
        expected,
    )
    typed = [
        candidate
        for candidate in named
        if receiver_matches(go_receiver, candidate.owner)
    ]
    # Go 顶层 `Test*` 只有映射到真实 Rust test harness 入口才算迁移；同名普通 helper
    # 不能冒充测试场景。方法/helper 的匹配规则保持不变。
    if kind == "test":
        typed = [candidate for candidate in typed if candidate.is_test_entry]
    selected, ambiguous = choose_unique(typed, expected)

    if selected is not None:
        detail_parts: list[str] = []
        if selected.path != expected:
            detail_parts.append("moved-from-expected-path")
        if selected.name == go_name and selected.name != mechanical_name:
            detail_parts.append("exact-go-name-preserved")
        return [
            go_location,
            kind,
            go_symbol,
            expected.as_posix(),
            selected.path.as_posix(),
            str(selected.line),
            selected.display_name,
            "migrated",
            "; ".join(detail_parts),
        ]

    constructors = associated_constructor_candidates(
        go_name, go_receiver, expected, rust_index
    )
    constructor_selected, constructor_ambiguous = choose_unique(constructors, expected)
    if constructor_selected is not None:
        return [
            go_location,
            kind,
            go_symbol,
            expected.as_posix(),
            constructor_selected.path.as_posix(),
            str(constructor_selected.line),
            constructor_selected.display_name,
            "migrated",
            "associated-constructor",
        ]

    documented = candidates_in_scope(
        (
            candidate
            for candidate in all_rust_symbols
            if documentation_mentions(candidate, go_name, go_receiver)
            and (kind != "test" or candidate.is_test_entry)
        ),
        expected,
    )
    documented_selected, documented_ambiguous = choose_unique(documented, expected)
    if documented_selected is not None:
        return [
            go_location,
            kind,
            go_symbol,
            expected.as_posix(),
            documented_selected.path.as_posix(),
            str(documented_selected.line),
            documented_selected.display_name,
            "migrated",
            "explicit-doc-mapping",
        ]

    if ambiguous or constructor_ambiguous or documented_ambiguous:
        unresolved = ambiguous or constructor_ambiguous or documented_ambiguous
        return [
            go_location,
            kind,
            go_symbol,
            expected.as_posix(),
            "",
            "",
            "",
            "ambiguous",
            candidate_detail(unresolved),
        ]

    # 仅把期望文件内唯一的 owner/kind 不符声明作为人工复核线索。跨文件同名项很可能
    # 属于另一个拆分模块或测试 fake，不能据此声称找到了实际迁移目标。
    exact_name_only = [candidate for candidate in named if candidate.path == expected]
    name_only, _ = choose_unique(exact_name_only, expected)
    if name_only is not None:
        expected_owner = go_receiver or "free-function"
        actual_owner = name_only.owner or "free-function"
        return [
            go_location,
            kind,
            go_symbol,
            expected.as_posix(),
            name_only.path.as_posix(),
            str(name_only.line),
            name_only.display_name,
            "name-only-match",
            f"owner mismatch: expected {expected_owner}, found {actual_owner}",
        ]

    same_name_detail = (
        f"; same-name declarations with different owner: {candidate_detail(named)}"
        if named
        else ""
    )
    return [
        go_location,
        kind,
        go_symbol,
        expected.as_posix(),
        "",
        "",
        "",
        "symbol-missing" if scope_exists else "pending",
        "no matching Rust declaration in package scope" + same_name_detail,
    ]


def generated_proto(relative: Path, source: str) -> bool:
    """只豁免 protoc-gen-go 输出，不把 DWARF 恢复源码误当自动生成代码。"""

    return (
        relative.parts[:2] == ("gen", "proto")
        and relative.name.endswith(".pb.go")
        and any(GENERATED_PROTO_HEADER in line for line in source.splitlines()[:5])
    )


def go_files(go_root: Path) -> list[Path]:
    """返回兼容门禁覆盖的 Go 根包、cmd、internal 与生成协议文件。"""

    roots = [go_root / "cmd", go_root / "internal", go_root / "gen"]
    # 根包现在包含 `main_test.go`。基线门禁会拒绝未审核的未跟踪 Go 文件，因此
    # 扫描全部 tracked/可见根级 `.go` 文件不会重新引入历史临时 probe 风险。
    files = list(go_root.glob("*.go"))
    for root in roots:
        if root.exists():
            files.extend(root.rglob("*.go"))
    return sorted(set(files))


def collect(go_root: Path, rust_root: Path) -> list[list[str]]:
    """收集文件和函数映射，并记录真实 Rust 声明位置或诚实缺项状态。"""

    rows: list[list[str]] = []
    rust_index = build_rust_index(rust_root)
    all_rust_symbols = [
        symbol for symbols in rust_index.values() for symbol in symbols
    ]
    rust_paths = {
        path.relative_to(rust_root) for path in (rust_root / "src").rglob("*.rs")
    }

    for source_path in go_files(go_root):
        relative = source_path.relative_to(go_root)
        expected = expected_rust_path(relative)
        source = source_path.read_text(encoding="utf-8")
        is_generated = generated_proto(relative, source)
        scope_exists = expected in rust_paths or any(
            is_within(path, expected.parent) for path in rust_paths
        )
        symbol_rows: list[list[str]] = []

        for line_number, line in enumerate(source.splitlines(), start=1):
            match = GO_FUNCTION.match(line)
            if match is None:
                continue
            name = match.group("name")
            receiver = receiver_type(match.group("receiver"))
            go_symbol = f"{receiver + '.' if receiver else ''}{name}"
            kind = "test" if name.startswith("Test") else ("method" if receiver else "function")
            go_location = f"{relative.as_posix()}:{line_number}"

            if is_generated:
                status = "generated-exempt" if expected in rust_paths else "generated-wrapper-missing"
                symbol_rows.append(
                    [
                        go_location,
                        kind,
                        go_symbol,
                        expected.as_posix(),
                        expected.as_posix() if expected in rust_paths else "",
                        "",
                        "",
                        status,
                        "protoc-gen-go API is regenerated by prost/pbjson in OUT_DIR; no 1:1 Rust symbol is asserted",
                    ]
                )
                continue

            symbol_rows.append(
                symbol_row(
                    go_location=go_location,
                    kind=kind,
                    go_symbol=go_symbol,
                    go_name=name,
                    go_receiver=receiver,
                    expected=expected,
                    rust_index=rust_index,
                    all_rust_symbols=all_rust_symbols,
                    scope_exists=scope_exists,
                )
            )

        if is_generated:
            file_status = "generated-wrapper" if expected in rust_paths else "generated-wrapper-missing"
            actual_path = expected.as_posix() if expected in rust_paths else ""
            detail = "checked-in wrapper includes prost/pbjson output from OUT_DIR"
        elif expected in rust_paths:
            file_status = "file-present"
            actual_path = expected.as_posix()
            detail = ""
        else:
            mapped_paths = sorted(
                {row[4] for row in symbol_rows if row[4] and row[7] == "migrated"}
            )
            if mapped_paths:
                file_status = "file-split"
                actual_path = ";".join(mapped_paths)
                detail = "Go file symbols are implemented in other Rust files"
            else:
                file_status = "pending"
                actual_path = ""
                detail = "expected Rust file is absent and no migrated symbol was found"

        rows.append(
            [
                relative.as_posix(),
                "file",
                "",
                expected.as_posix(),
                actual_path,
                "",
                "",
                file_status,
                detail,
            ]
        )
        rows.extend(symbol_rows)

    return rows


def render(rows: list[list[str]]) -> str:
    """将映射以稳定的 CSV 顺序序列化。"""

    with tempfile.SpooledTemporaryFile(mode="w+", newline="", encoding="utf-8") as output:
        writer = csv.writer(output, lineterminator="\n")
        writer.writerow(CSV_HEADER)
        writer.writerows(rows)
        output.seek(0)
        return output.read()


def print_summary(rows: list[list[str]]) -> None:
    """向 stderr 输出按状态分类的稳定摘要，便于 CI 和迁移收尾复核。"""

    counts = Counter(row[7] for row in rows)
    print(f"symbol-map rows: {len(rows)}", file=sys.stderr)
    for status, count in sorted(counts.items()):
        print(f"  {status}: {count}", file=sys.stderr)


def main() -> int:
    """生成清单；check 校验新鲜度，require-complete 拒绝所有未确认映射。"""

    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--go-root",
        type=Path,
        default=Path(
            os.environ.get(
                "GO_SOURCE_ROOT", "/Users/arthur/GolandProjects/environment-manager"
            )
        ),
    )
    parser.add_argument(
        "--rust-root", type=Path, default=Path(__file__).resolve().parents[2]
    )
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--summary", action="store_true")
    parser.add_argument(
        "--require-complete",
        action="store_true",
        help="只要存在 pending、missing、ambiguous 或未经确认的同名候选就返回失败",
    )
    parser.add_argument(
        "--expected-go-tests",
        type=int,
        help="要求 Go 顶层 Test* 场景总数及 migrated 数量都精确等于该值",
    )
    arguments = parser.parse_args()

    go_root = arguments.go_root.resolve()
    rust_root = arguments.rust_root.resolve()
    if not go_root.is_dir():
        parser.error(f"Go source root does not exist: {go_root}")
    if not (rust_root / "src").is_dir():
        parser.error(f"Rust source root does not contain src/: {rust_root}")

    target = rust_root / "compat" / "go-rust-symbols.csv"
    rows = collect(go_root, rust_root)
    content = render(rows)
    if arguments.summary:
        print_summary(rows)

    if arguments.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            print(f"stale symbol map: regenerate {target}", file=sys.stderr)
            return 1
        if arguments.expected_go_tests is not None:
            go_tests = [row for row in rows if row[1] == "test"]
            migrated_tests = [row for row in go_tests if row[7] == "migrated"]
            print(
                "Go test scenarios: "
                f"{len(migrated_tests)}/{len(go_tests)} migrated "
                f"(expected {arguments.expected_go_tests})",
                file=sys.stderr,
            )
            if (
                len(go_tests) != arguments.expected_go_tests
                or len(migrated_tests) != arguments.expected_go_tests
            ):
                return 3
        if arguments.require_complete:
            incomplete = Counter(row[7] for row in rows if row[7] in INCOMPLETE_STATUSES)
            if incomplete:
                print("incomplete symbol mappings:", file=sys.stderr)
                for status, count in sorted(incomplete.items()):
                    print(f"  {status}: {count}", file=sys.stderr)
                return 2
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(".csv.tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(target)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
